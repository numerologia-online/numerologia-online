function fpKnowledge(): array {
    static $all=null;
    if($all!==null)return $all;
    $raw=@file_get_contents(__DIR__.'/family-owner-knowledge-v1.txt');
    if(!is_string($raw)||mb_strlen($raw,'UTF-8')>16000)
        throw new RuntimeException('FAMILY_PRACTICAL_KB_UNAVAILABLE');
    $lines=preg_split('/\R/u',trim($raw));
    if(!is_array($lines)||count($lines)!==23)
        throw new RuntimeException('FAMILY_PRACTICAL_KB_22_INVALID');
    $ids=fpQuestionIds();
    if(array_shift($lines)!=='energy|'.implode('|',$ids))
        throw new RuntimeException('FAMILY_PRACTICAL_KB_COLUMNS_INVALID');
    $found=[];
    foreach($lines as $line){
        $parts=explode('|',$line);
        $num=array_shift($parts);
        if(count($parts)!==count($ids)||!ctype_digit($num))
            throw new RuntimeException('FAMILY_PRACTICAL_KB_ENTRY_INVALID');
        $number=(int)$num;
        if($number<1||$number>22||isset($found[$number]))
            throw new RuntimeException('FAMILY_PRACTICAL_KB_NUMBER_INVALID');
        $values=array_map('trim',$parts);
        foreach($values as $v)if($v===''||mb_strlen($v,'UTF-8')>160)
            throw new RuntimeException('FAMILY_PRACTICAL_KB_KEY_INVALID');
        $found[$number]=array_combine($ids,$values);
    }
    for($i=1;$i<=22;$i++)if(!isset($found[$i]))
        throw new RuntimeException('FAMILY_PRACTICAL_KB_INCOMPLETE');
    return $all=$found;
}
