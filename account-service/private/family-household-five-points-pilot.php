function nfhPilotBrief(int $day,int $month,int $year): array {
    if($year<1900||$year>(int)gmdate('Y')||!checkdate($month,$day,$year))
        throw new InvalidArgumentException('FAMILY_PILOT_INVALID_DATE');
    $points=ni31($day,$month,$year);
    $dictionary=nfhPilotEnergies();
    $roles=[
      'left'=>'Главная позиция: как лично действует в повседневности',
      'top'=>'Главная позиция: как относится к повторяющейся рутине',
      'wellbeing'=>'Дополнение: режим и обстановка дома',
      'bottom'=>'Дополнение: ответственность в трудностях',
      'rightNear'=>'Дополнение: выполнение конкретной задачи'
    ];
    $five=[];
    foreach($roles as $key=>$role){
        $n=$points[$key];
        if(!isset($dictionary[$n]))throw new RuntimeException('FAMILY_PILOT_ENERGY_MISSING');
        $five[]=[
            'role'=>$role, 'energy'=>$n,
            'meaning'=>$dictionary[$n][0], 'shadow'=>$dictionary[$n][1]
        ];
    }
    return [
      'question'=>'Хозяйственный или из серии «мама всё делала»?',
      'rule'=>'Энергия дня ведущая. Энергия месяца и три дополнительные позиции обязательно участвуют в синтезе и способны заметно изменить результат.',
      'five'=>$five
    ];
}

function nfhPilotModelData(array $brief): array {
    if(count($brief['five']??[])!==5)throw new InvalidArgumentException('FAMILY_PILOT_FIVE_REQUIRED');
    $clean=[];
    foreach($brief['five'] as $point){
        $clean[]=['роль'=>$point['role'],'проявление'=>$point['meaning'],'тень'=>$point['shadow']];
    }
    // Never reveal numeric birth details in customer-facing prose.
    return [
      'вопрос'=>$brief['question'],
      'ведущая_энергия_дня'=>$clean[0],
      'четыре_обязательных_влияния'=>array_slice($clean,1),
      'следующий_вопрос'=>'Он заботится в быту или ждёт, что любовь всё сама устроит?'
    ];
}

