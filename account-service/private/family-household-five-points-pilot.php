function nfhPilotVerdict(int $sum): string {
    if($sum>=3)return 'Склонен поддерживать бытовой порядок регулярно. Важно отличить самостоятельную работу от командования другими.';
    if($sum>=1)return 'Бытовая включённость есть, но проявляется неравномерно. Не называй его ни неряхой, ни идеальным домохозяином.';
    if($sum===0)return 'Противоречивый бытовой характер: есть полезная склонность и встречное сопротивление рутине. Покажи обе стороны конкретно, не переворачивая главную пару.';
    if($sum>=-2)return 'С регулярными домашними обязанностями вероятны трудности; отдельные полезные поступки не доказывают хозяйственности.';
    return 'Скучные повседневные обязанности скорее будет перекладывать; разовая инициатива и способность решать проблемы этого не отменяют.';
}

function nfhPilotBrief(int $day,int $month,int $year): array {
    if($year<1900||$year>(int)gmdate('Y')||!checkdate($month,$day,$year))
        throw new InvalidArgumentException('FAMILY_PILOT_INVALID_DATE');
    $points=ni31($day,$month,$year);
    $dictionary=nfhPilotEnergies();
    $roles=[
      'left'=>'Главная позиция: как лично действует в повседневности',
      'top'=>'Главная позиция: как относится к повторяющейся рутине',
      'wellbeing'=>'Дополнение: режим и обстановка дома',
      'bottom'=>'Дополнение: ответственность в трудностях',
      'rightNear'=>'Дополнение: выполнение конкретной задачи'
    ];
    $five=[];
    foreach($roles as $key=>$role){
        $n=$points[$key];
        if(!isset($dictionary[$n]))throw new RuntimeException('FAMILY_PILOT_ENERGY_MISSING');
        $five[]=[
            'role'=>$role, 'energy'=>$n,
            'meaning'=>$dictionary[$n][1], 'shadow'=>$dictionary[$n][2]
        ];
    }
    $score=$dictionary[$points['left']][0]+$dictionary[$points['top']][0];
    return [
      'question'=>'Хозяйственный или из серии «мама всё делала»?',
      'rule'=>'Ровно пять точек: день и месяц по 50/50 составляют основной вывод; остальные три только уточняют его.',
      'score'=>$score,
      'verdict'=>nfhPilotVerdict($score),
      'five'=>$five
    ];
}

function nfhPilotModelData(array $brief): array {
    if(count($brief['five']??[])!==5)throw new InvalidArgumentException('FAMILY_PILOT_FIVE_REQUIRED');
    $clean=[];
    foreach($brief['five'] as $point){
        $clean[]=['роль'=>$point['role'],'проявление'=>$point['meaning'],'тень'=>$point['shadow']];
    }
    // Neither model nor customer receives birth numbers or calculation scores.
    return [
      'вопрос'=>$brief['question'],
      'фиксированный_главный_вывод'=>$brief['verdict'],
      'две_равные_главные_позиции'=>array_slice($clean,0,2),
      'три_уточняющие_позиции_не_меняют_вывод'=>array_slice($clean,2),
      'следующий_вопрос'=>'Он заботится в быту или ждёт, что любовь всё сама устроит?'
    ];
}

