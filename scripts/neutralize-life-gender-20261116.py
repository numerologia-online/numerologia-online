def neutralize(n,section,text):
    for old,new in R.get(n,{}).get(section,[]):
        text=text.replace(old,new)
    for old,new in SHARED:
        text=text.replace(old,new)
    if section in {"trueLove","partner"}:
        for old,new in PARTNER_FORMS:
            text=re.sub(old,new,text)
    return text

def patch_source(raw,old,new,path):
    if old==new:
        return raw
    q_old=json.dumps(old,ensure_ascii=False)
    q_new=json.dumps(new,ensure_ascii=False)
    count=raw.count(q_old)
    if count < 1:
        raise AssertionError(("TEXT_SOURCE_NOT_FOUND",path,old[:80]))
    return raw.replace(q_old,q_new)

def prepare():
    updates=[]
    gender_warnings=[]
    for n in range(1,23):
        file=REPO_PATH/f"energy-{n}.json"
        raw=file.read_text("utf-8")
        d=json.loads(raw.lstrip("\ufeff"))
        after=raw
        changed=[]
        for section_name,section in d["sections"].items():
            for key in ("content","paragraphs"):
                if key not in section: continue
                vals=section[key]
                if isinstance(vals,str):
                    amended=neutralize(n,section_name,vals)
                    if amended!=vals:
                        after=patch_source(after,vals,amended,str(file))
                        changed.append(section_name+"/content")
                elif isinstance(vals,list):
                    for p in vals:
                        amended=neutralize(n,section_name,p)
                        if amended!=p:
                            after=patch_source(after,p,amended,str(file))
                            changed.append(section_name+"/paragraph")
            # Verify that paired content and paragraphs match whenever they matched previously.
            before_sec=section
            after_sec=json.loads(after.lstrip("\ufeff"))["sections"][section_name]
            if "content" in before_sec and "paragraphs" in before_sec:
                if before_sec["content"]=="\n\n".join(before_sec["paragraphs"]):
                    assert after_sec["content"]=="\n\n".join(after_sec["paragraphs"]),("SOURCE_PDF_MISMATCH",n,section_name)
        revised=json.loads(after.lstrip("\ufeff"))
        assert list(revised["sections"])==list(d["sections"])
        for k in d["sections"]:
            assert set(revised["sections"][k])==set(d["sections"][k])
        if after!=raw:
            file.write_text(after,"utf8")
            updates.append((str(file),hashlib.sha256(raw.encode()).hexdigest(),hashlib.sha256(after.encode()).hexdigest(),len(changed)))
        # Scan the final reader-facing text for remaining assumptions (report only).
        for key,section in revised["sections"].items():
            for i,p in enumerate(section.get("paragraphs",[])):
                if re.search(r"\b(?:женщин(?:а|у|е|ой|ы)?|мужчин(?:а|у|е|ой|ы)?|девушк[а-яё]*|вы [а-яё ,]{0,30}(?:сильной|удобной|красивой|готовой|одной|женщиной))\b",p,re.I):
                    gender_warnings.append((n,key,i,p[:100]))
    manifest=json.loads(MANIFEST.read_text("utf8"))
    assert manifest["version"]==2
    for name,old_hash,new_hash,_ in updates:
        if manifest["files"].get(name)!=old_hash:
            raise AssertionError(("PRIVATE_MANIFEST_SOURCE_CONFLICT",name,manifest["files"].get(name),old_hash))
        manifest["files"][name]=new_hash
    if updates:
        old_text=MANIFEST.read_text("utf8")
        new_text=old_text
        for name,old_hash,new_hash,_ in updates:
            old_ref=json.dumps(name,ensure_ascii=False)+": "+json.dumps(old_hash)
            new_ref=json.dumps(name,ensure_ascii=False)+": "+json.dumps(new_hash)
            assert new_text.count(old_ref)==1,("MANIFEST_LOCATION_UNEXPECTED",name)
            new_text=new_text.replace(old_ref,new_ref)
        MANIFEST.write_text(new_text,"utf8")
    pathlib.Path("/tmp/numi-life-gender-release.json").write_text(json.dumps({"updates":updates},ensure_ascii=False),"utf8")
    print("NEUTRAL_LIFE_SOURCE_UPDATES",len(updates),flush=True)
    for u in updates:print("TEXT_CHANGED",u[0],"elements",u[3],flush=True)
    print("REMAINING_GENDER_TERMS",len(gender_warnings),flush=True)
    for row in gender_warnings[:100]:print("REVIEW",*row,flush=True)
    return len(updates)

if __name__=="__main__":
    assert len(sys.argv)==2 and sys.argv[1]=="prepare"
    prepare()
