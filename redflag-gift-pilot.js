const periodNote = (profile) => {
  const { personalMonth, dayEnergy, lifeEnergy, agePeriod } = profile;
  const theme = [1, 3, 5].includes(personalMonth) ? "momentum"
    : [2, 6].includes(personalMonth) ? "closeness"
      : [4, 8].includes(personalMonth) ? "reality"
        : "reflection";
  const notes = PERIOD_NOTES[theme];
  return notes[(dayEnergy * 19 + lifeEnergy * 7 + agePeriod.energy * 13 + personalMonth * 3) % notes.length];
};

/** Returns one whole, stable answer and two question-specific scales. */
export const answerGiftPilot = (birthDate, now = new Date()) => {
  const profile = buildRedFlagProfile(birthDate, now);
  const day = GIFT_TRAITS[profile.dayEnergy];
  const life = GIFT_TRAITS[profile.lifeEnergy];
  const period = GIFT_TRAITS[profile.agePeriod.energy];
  const giving = weighted(day, life, period, "giving");
  const display = weighted(day, life, period, "display");
  const regularity = weighted(day, life, period, "regularity");
  const selected = ANSWERS[day.style];

  return {
    profile,
    scales: [
      { label: "Готовность дарить", value: giving },
      { label: "Риск подарка ради впечатления", value: display }
    ],
    regularity,
    verdict: selected.verdict,
    paragraphs: [...selected.paragraphs, periodNote(profile)],
    observation: selected.observation
  };
};
